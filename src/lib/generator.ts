function pick<T>(arr: T[]): T {
  return arr[Math.floor(Math.random() * arr.length)];
}

function randInt(min: number, max: number): number {
  return Math.floor(min + Math.random() * (max - min + 1));
}

export function generateCatomon(photo: string, aiData?: Partial<Catomon>): Catomon {
  const types: CatomonType[] = ["fire", "water", "grass", "electric", "psychic", "normal", "dark", "fairy", "fighting", "ghost", "ice", "rock"];
  const type = aiData?.type ?? pick(types);
  const hasSubtype = Math.random() > 0.7;
  const subtype = hasSubtype ? pick(types.filter((t) => t !== type)) : undefined;

  const prefixesMap: Record<CatomonType, string[]> = {
    fire: PREFIXES_FIRE, water: PREFIXES_WATER, grass: PREFIXES_GRASS, electric: PREFIXES_ELECTRIC,
    psychic: PREFIXES_PSYCHIC, normal: PREFIXES_NORMAL, dark: PREFIXES_DARK, fairy: PREFIXES_FAIRY,
    fighting: PREFIXES_FIGHTING, ghost: PREFIXES_GHOST, ice: PREFIXES_ICE, rock: PREFIXES_ROCK,
  };

  const name = aiData?.name ?? `${pick(prefixesMap[type])}${pick(SUFFIXES)}`;

  const allMoves = MOVES_BY_TYPE[type];
  const move1: CatomonMove = {
    name: aiData?.moves?.[0]?.name ?? pick(allMoves),
    power: aiData?.moves?.[0]?.power ?? randInt(30, 85),
    type: type,
  };
  const move2: CatomonMove = {
    name: aiData?.moves?.[1]?.name ?? pick(subtype ? MOVES_BY_TYPE[subtype] : allMoves),
    power: aiData?.moves?.[1]?.power ?? randInt(20, 95),
    type: subtype ?? type,
  };

  const rarityRoll = Math.random();
  let rarity: Catomon["rarity"];
  if (rarityRoll > 0.97) rarity = "legendary";
  else if (rarityRoll > 0.88) rarity = "epic";
  else if (rarityRoll > 0.65) rarity = "rare";
  else if (rarityRoll > 0.35) rarity = "uncommon";
  else rarity = "common";

  const rarityBonus = { common: 0, uncommon: 10, rare: 20, epic: 35, legendary: 50 }[rarity];

  return {
    id: aiData?.id ?? crypto.randomUUID(),
    name,
    type,
    subtype,
    title: aiData?.title ?? pick(TITLES),
    description: aiData?.description ?? pick(DESCRIPTIONS_BY_TYPE[type]),
    rarity,
    stats: aiData?.stats ?? {
      hp: randInt(35, 75) + rarityBonus,
      attack: randInt(30, 80) + rarityBonus,
      defense: randInt(25, 75) + rarityBonus,
      speed: randInt(40, 95) + rarityBonus,
      special: randInt(30, 90) + rarityBonus,
    },
    moves: [move1, move2],
    ability: aiData?.ability ?? pick(ABILITIES_BY_TYPE[type]),
    height: aiData?.height ?? `${randInt(20, 55)} см`,
    weight: aiData?.weight ?? `${(randInt(25, 85) / 10).toFixed(1)} кг`,
    photo,
    createdAt: Date.now(),
  };
}
